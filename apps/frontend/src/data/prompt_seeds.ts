function hash32(s: string): number {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function pick<T>(arr: T[], seed: number, salt: number): T {
  return arr[(seed + salt) % arr.length];
}

function detailSeed(base: string): string {
  // Keep adult subject; avoid duplicating attributes already in base.
  const seed = hash32(base);
  const skins = ['golden tan', 'light olive', 'porcelain', 'neutral beige', 'soft caramel'];
  const hairColors = ['ash blonde', 'chestnut brown', 'raven black', 'honey blonde', 'copper auburn'];
  const hairLengths = ['waist length', 'mid back', 'shoulder length', 'long'];
  const hairStyles = ['loose waves', 'straight layers', 'soft curls', 'gentle waves'];
  const eyeColors = ['blue', 'hazel', 'green', 'warm brown', 'steel gray'];
  const eyeShapes = ['almond', 'upturned', 'round'];

  const has = (w: string) => new RegExp(`\\b${w}\\b`, 'i').test(base);
  const hasHair = () => /\bhair\b|\bwaves?\b|\bcurls?\b|\bbraid\b|\bbob\b|\blob\b|\bponytail\b|\bupdo\b|\btwists?\b|\bcoils?\b|\bbun\b|\bbangs\b|\blayers?\b|\bpuff\b/i.test(base);
  const hasSkin = () => /\bskin\b|\bcomplexion\b|\bundertone\b/i.test(base);
  const parts: string[] = [];

  // Only include attributes that are not already present in the base string.
  if (!hasSkin()) parts.push(`${pick(skins, seed, 1)} skin`);
  if (!hasHair()) parts.push(`${pick(hairLengths, seed, 2)} ${pick(hairColors, seed, 3)} hair, ${pick(hairStyles, seed, 4)}`);
  if (!has('eyes')) parts.push(`${pick(eyeColors, seed, 5)} ${pick(eyeShapes, seed, 6)} eyes`);
  if (!/smile|expression|gaze|look/i.test(base)) parts.push('soft natural smile');

  const anchor = base.replace(/\.$/, '');
  return parts.length ? `${anchor}, ${parts.join(', ')}` : anchor;
}

export function getRandomSeed(): string | null {
  if (!Array.isArray(PROMPT_SEEDS) || PROMPT_SEEDS.length === 0) return null;
  const i = Math.floor(Math.random() * PROMPT_SEEDS.length);
  const base = PROMPT_SEEDS[i] || '';
  try {
    return detailSeed(base);
  } catch {
    return base;
  }
}
