/**
 * Generate SEO-friendly alt text for AI-generated images
 *
 * @param prompt - The generation prompt (optional)
 * @param isVideoThumbnail - Whether this is a video thumbnail (optional)
 * @returns Alt text for the image
 */
const ALT_SUFFIX = ' – Generated by Girl Generator';
const MAX_ALT_LENGTH = 120;

function truncateForAlt(text: string): string {
  const normalized = text.replace(/\s+/g, ' ').trim();
  if (!normalized) return '';

  const words = normalized.split(' ').filter(Boolean);
  const baseWords = words.slice(0, 8).join(' ');
  let base = (baseWords || normalized).trim();

  const maxBaseLength = Math.max(10, MAX_ALT_LENGTH - ALT_SUFFIX.length);
  if (base.length > maxBaseLength) {
    let truncated = base.slice(0, maxBaseLength).trim();
    const lastSpace = truncated.lastIndexOf(' ');
    if (lastSpace > 0 && base.length > maxBaseLength) {
      truncated = truncated.slice(0, lastSpace).trim();
    }
    if (!truncated) {
      truncated = base.slice(0, maxBaseLength).trim();
    }
    base = truncated;
  }

  return `${base}${ALT_SUFFIX}`;
}

export function generateImageAlt(prompt?: string | null, isVideoThumbnail?: boolean): string {
  // Case 1: Has prompt
  if (prompt && typeof prompt === 'string' && prompt.trim().length > 0) {
    return truncateForAlt(prompt);
  }

  // Case 2: No prompt, video thumbnail
  if (isVideoThumbnail) {
    return 'AI-generated girl video thumbnail – by Girl Generator';
  }

  // Case 3: No prompt, regular image
  return 'AI-generated girl image – by Girl Generator';
}
